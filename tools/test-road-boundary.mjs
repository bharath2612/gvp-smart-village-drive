import assert from 'node:assert/strict';
import { RoadBoundary } from '../src/world/road-boundary.js';
import { ColliderGrid } from '../src/world/spatial.js';
const grid = new ColliderGrid(), b = new RoadBoundary(grid);
const rect = (x,z,w,h) => [[x,z],[x+w,z],[x+w,z+h],[x,z+h]];
b.add(rect(0,0,100,10),'road'); b.add(rect(0,0,100,2),'blocked'); b.add(rect(0,8,100,2),'blocked');
b.add(rect(40,-30,10,70),'access');
assert(b.fits(20,5,Math.PI/2,2.3,.95));
assert(!b.fits(20,2.6,Math.PI/2,2.3,.95),'body, not centre, must remain on carriageway');
assert(b.fits(45,5,0,2.3,.95),'crossing union has no seam');
assert(b.fits(64,5,Math.PI/2,2.3,.95),'grid seam is traversable');
b.add(rect(18,4.95,4,.1),'forbidden');
assert(!b.fits(20,5,Math.PI/2,2.3,.95),'thin hole inside footprint, missed by corner sampling');
const c={px:30,pz:5,pyaw:0,x:30,z:25,yaw:0,vx:0,vz:100,halfL:2.3,halfW:.95};
b.add(rect(0,20,100,10),'access'); b.constrain(c);
assert(c.z<6 && b.fits(c.x,c.z,c.yaw,c.halfL,c.halfW),'swept movement cannot tunnel between separated roads');
const d={px:30,pz:4,pyaw:Math.PI/2,x:30,z:4,yaw:0,vx:0,vz:0,halfL:2.3,halfW:.95};b.constrain(d);
assert(b.fits(d.x,d.z,d.yaw,d.halfL,d.halfW),'rotation respects kerb');
b.seeds.push({x:0,z:5,bx:100,bz:5,offsets:[0]});grid.add(28,3,33,7,'car');
const p=b.nearest(30,12,Math.PI/2,2.3,.95);assert(b.clear(p.x,p.z,p.yaw,2.3,.95),'recovery avoids parked car');
const angled=new RoadBoundary(new ColliderGrid());angled.add([[-20,-20],[-12,-28],[28,12],[20,20]]);
assert(angled.fits(4,-4,Math.PI*.75,2.3,.95));assert(!angled.fits(10,-10,Math.PI*.75,2.3,.95));
console.log('Road boundaries: footprint, thin holes, junctions, tile seams, swept movement, rotation, rotated road, occupied recovery passed.');
